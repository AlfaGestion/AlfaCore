SET NOCOUNT ON;

IF OBJECT_ID(N'dbo.POS_PUNTOVENTA', N'U') IS NULL
    RETURN;

DECLARE @sql nvarchar(max) = N'';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'GOUR_CANTIDAD1') IS NULL SET @sql = @sql + N'ALTER TABLE dbo.POS_PUNTOVENTA ADD GOUR_CANTIDAD1 decimal(18, 4) NULL;';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'GOUR_CANTIDAD2') IS NULL SET @sql = @sql + N'ALTER TABLE dbo.POS_PUNTOVENTA ADD GOUR_CANTIDAD2 decimal(18, 4) NULL;';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'GOUR_CANTIDAD3') IS NULL SET @sql = @sql + N'ALTER TABLE dbo.POS_PUNTOVENTA ADD GOUR_CANTIDAD3 decimal(18, 4) NULL;';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'GOUR_CANTIDAD4') IS NULL SET @sql = @sql + N'ALTER TABLE dbo.POS_PUNTOVENTA ADD GOUR_CANTIDAD4 decimal(18, 4) NULL;';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'GOUR_CANTIDAD5') IS NULL SET @sql = @sql + N'ALTER TABLE dbo.POS_PUNTOVENTA ADD GOUR_CANTIDAD5 decimal(18, 4) NULL;';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'GOUR_CANTIDAD6') IS NULL SET @sql = @sql + N'ALTER TABLE dbo.POS_PUNTOVENTA ADD GOUR_CANTIDAD6 decimal(18, 4) NULL;';
IF @sql <> N'' EXEC sys.sp_executesql @sql;
GO

UPDATE dbo.POS_PUNTOVENTA
SET GOUR_CANTIDAD1 = ISNULL(GOUR_CANTIDAD1, 0.1),
    GOUR_CANTIDAD2 = ISNULL(GOUR_CANTIDAD2, 0.25),
    GOUR_CANTIDAD3 = ISNULL(GOUR_CANTIDAD3, 0.5),
    GOUR_CANTIDAD4 = ISNULL(GOUR_CANTIDAD4, 1),
    GOUR_CANTIDAD5 = ISNULL(GOUR_CANTIDAD5, 6),
    GOUR_CANTIDAD6 = ISNULL(GOUR_CANTIDAD6, 12)
WHERE GOUR_CANTIDAD1 IS NULL OR GOUR_CANTIDAD2 IS NULL OR GOUR_CANTIDAD3 IS NULL
   OR GOUR_CANTIDAD4 IS NULL OR GOUR_CANTIDAD5 IS NULL OR GOUR_CANTIDAD6 IS NULL;
