IF NOT EXISTS (
    SELECT 1
    FROM dbo.TA_CONFIGURACION
    WHERE UPPER(LTRIM(RTRIM(CLAVE))) = N'VIAJES-ADICIONAL-3-SUMAR-FLETERO'
)
    INSERT INTO dbo.TA_CONFIGURACION (GRUPO, CLAVE, VALOR, DESCRIPCION, FechaHora_Grabacion)
    VALUES (@Grupo, N'VIAJES-ADICIONAL-3-SUMAR-FLETERO', N'false', NULL, GETDATE());

IF NOT EXISTS (
    SELECT 1
    FROM dbo.TA_CONFIGURACION
    WHERE UPPER(LTRIM(RTRIM(CLAVE))) = N'VIAJES-ADICIONAL-4-SUMAR-FLETERO'
)
    INSERT INTO dbo.TA_CONFIGURACION (GRUPO, CLAVE, VALOR, DESCRIPCION, FechaHora_Grabacion)
    VALUES (@Grupo, N'VIAJES-ADICIONAL-4-SUMAR-FLETERO', N'false', NULL, GETDATE());

IF NOT EXISTS (
    SELECT 1
    FROM dbo.TA_CONFIGURACION
    WHERE UPPER(LTRIM(RTRIM(CLAVE))) = N'VIAJES-ADICIONAL-5-SUMAR-FLETERO'
