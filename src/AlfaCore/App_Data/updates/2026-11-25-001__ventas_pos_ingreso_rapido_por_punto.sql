SET NOCOUNT ON;

-- Configuración individual del panel de ingreso rápido por punto de venta.
-- No modifica TA_CONFIGURACION ni crea tablas nuevas.
IF OBJECT_ID(N'dbo.POS_PUNTOVENTA', N'U') IS NULL
    RETURN;

DECLARE @sql nvarchar(max) = N'';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'CARGARAPIDAGRAFICA') IS NULL
    SET @sql = @sql + N'ALTER TABLE dbo.POS_PUNTOVENTA ADD CARGARAPIDAGRAFICA bit NULL;';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'GOUR_IMPORTE1') IS NULL
    SET @sql = @sql + N'ALTER TABLE dbo.POS_PUNTOVENTA ADD GOUR_IMPORTE1 decimal(18, 4) NULL;';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'GOUR_IMPORTE2') IS NULL
    SET @sql = @sql + N'ALTER TABLE dbo.POS_PUNTOVENTA ADD GOUR_IMPORTE2 decimal(18, 4) NULL;';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'GOUR_IMPORTE3') IS NULL
    SET @sql = @sql + N'ALTER TABLE dbo.POS_PUNTOVENTA ADD GOUR_IMPORTE3 decimal(18, 4) NULL;';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'GOUR_IMPORTE4') IS NULL
    SET @sql = @sql + N'ALTER TABLE dbo.POS_PUNTOVENTA ADD GOUR_IMPORTE4 decimal(18, 4) NULL;';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'GOUR_IMPORTE5') IS NULL
    SET @sql = @sql + N'ALTER TABLE dbo.POS_PUNTOVENTA ADD GOUR_IMPORTE5 decimal(18, 4) NULL;';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'GOUR_IMPORTE6') IS NULL
    SET @sql = @sql + N'ALTER TABLE dbo.POS_PUNTOVENTA ADD GOUR_IMPORTE6 decimal(18, 4) NULL;';
IF @sql <> N''
    EXEC sys.sp_executesql @sql;
GO

UPDATE dbo.POS_PUNTOVENTA
SET GOUR_IMPORTE1 = ISNULL(GOUR_IMPORTE1, 5),
    GOUR_IMPORTE2 = ISNULL(GOUR_IMPORTE2, 10),
    GOUR_IMPORTE3 = ISNULL(GOUR_IMPORTE3, 25),
    GOUR_IMPORTE4 = ISNULL(GOUR_IMPORTE4, 50),
    GOUR_IMPORTE5 = ISNULL(GOUR_IMPORTE5, 100),
    GOUR_IMPORTE6 = ISNULL(GOUR_IMPORTE6, 200),
    CARGARAPIDAGRAFICA = ISNULL(CARGARAPIDAGRAFICA, 0)
WHERE GOUR_IMPORTE1 IS NULL OR GOUR_IMPORTE2 IS NULL OR GOUR_IMPORTE3 IS NULL
   OR GOUR_IMPORTE4 IS NULL OR GOUR_IMPORTE5 IS NULL OR GOUR_IMPORTE6 IS NULL
   OR CARGARAPIDAGRAFICA IS NULL;
