SET NOCOUNT ON;

-- Configuración del recibo de anticipo por punto de venta.
-- No crea tablas nuevas: amplía POS_PUNTOVENTA, que ya es la configuración individual del POS.
IF OBJECT_ID(N'dbo.POS_PUNTOVENTA', N'U') IS NULL
    RETURN;

DECLARE @sql nvarchar(max) = N'';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'RECIBO_ANTICIPO_MODALIDAD') IS NULL
    SET @sql += N'ALTER TABLE dbo.POS_PUNTOVENTA ADD RECIBO_ANTICIPO_MODALIDAD varchar(12) NULL;';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'RECIBO_ANTICIPO_FORMATO') IS NULL
    SET @sql += N'ALTER TABLE dbo.POS_PUNTOVENTA ADD RECIBO_ANTICIPO_FORMATO varchar(10) NULL;';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'RECIBO_ANTICIPO_EMPRESA') IS NULL
    SET @sql += N'ALTER TABLE dbo.POS_PUNTOVENTA ADD RECIBO_ANTICIPO_EMPRESA bit NULL;';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'RECIBO_ANTICIPO_PEDIDO') IS NULL
    SET @sql += N'ALTER TABLE dbo.POS_PUNTOVENTA ADD RECIBO_ANTICIPO_PEDIDO bit NULL;';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'RECIBO_ANTICIPO_CLIENTE') IS NULL
    SET @sql += N'ALTER TABLE dbo.POS_PUNTOVENTA ADD RECIBO_ANTICIPO_CLIENTE bit NULL;';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'RECIBO_ANTICIPO_IMPORTES') IS NULL
    SET @sql += N'ALTER TABLE dbo.POS_PUNTOVENTA ADD RECIBO_ANTICIPO_IMPORTES bit NULL;';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'RECIBO_ANTICIPO_MEDIOS') IS NULL
    SET @sql += N'ALTER TABLE dbo.POS_PUNTOVENTA ADD RECIBO_ANTICIPO_MEDIOS bit NULL;';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'RECIBO_ANTICIPO_ENTREGA') IS NULL
    SET @sql += N'ALTER TABLE dbo.POS_PUNTOVENTA ADD RECIBO_ANTICIPO_ENTREGA bit NULL;';
IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'RECIBO_ANTICIPO_USUARIO') IS NULL
    SET @sql += N'ALTER TABLE dbo.POS_PUNTOVENTA ADD RECIBO_ANTICIPO_USUARIO bit NULL;';
-- El UPDATE también va dentro de SQL dinámico: si las columnas son nuevas,
-- SQL Server no permite referenciarlas en el mismo lote que el ALTER TABLE.
IF @sql <> N''
    EXEC sys.sp_executesql @sql;

SET @sql = N'
UPDATE dbo.POS_PUNTOVENTA
SET RECIBO_ANTICIPO_MODALIDAD = ISNULL(NULLIF(LTRIM(RTRIM(RECIBO_ANTICIPO_MODALIDAD)), ''''), ''NO''),
    RECIBO_ANTICIPO_FORMATO = ISNULL(NULLIF(LTRIM(RTRIM(RECIBO_ANTICIPO_FORMATO)), ''''), ''TICKET80''),
    RECIBO_ANTICIPO_EMPRESA = ISNULL(RECIBO_ANTICIPO_EMPRESA, 1),
    RECIBO_ANTICIPO_PEDIDO = ISNULL(RECIBO_ANTICIPO_PEDIDO, 1),
    RECIBO_ANTICIPO_CLIENTE = ISNULL(RECIBO_ANTICIPO_CLIENTE, 1),
    RECIBO_ANTICIPO_IMPORTES = ISNULL(RECIBO_ANTICIPO_IMPORTES, 1),
    RECIBO_ANTICIPO_MEDIOS = ISNULL(RECIBO_ANTICIPO_MEDIOS, 1),
    RECIBO_ANTICIPO_ENTREGA = ISNULL(RECIBO_ANTICIPO_ENTREGA, 1),
    RECIBO_ANTICIPO_USUARIO = ISNULL(RECIBO_ANTICIPO_USUARIO, 1)
WHERE RECIBO_ANTICIPO_MODALIDAD IS NULL
   OR RECIBO_ANTICIPO_FORMATO IS NULL
   OR RECIBO_ANTICIPO_EMPRESA IS NULL
   OR RECIBO_ANTICIPO_PEDIDO IS NULL
   OR RECIBO_ANTICIPO_CLIENTE IS NULL
   OR RECIBO_ANTICIPO_IMPORTES IS NULL
   OR RECIBO_ANTICIPO_MEDIOS IS NULL
   OR RECIBO_ANTICIPO_ENTREGA IS NULL
   OR RECIBO_ANTICIPO_USUARIO IS NULL;';

EXEC sys.sp_executesql @sql;
