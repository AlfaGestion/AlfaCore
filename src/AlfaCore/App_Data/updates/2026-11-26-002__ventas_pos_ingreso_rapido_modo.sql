SET NOCOUNT ON;

IF OBJECT_ID(N'dbo.POS_PUNTOVENTA', N'U') IS NULL
    RETURN;

IF COL_LENGTH(N'dbo.POS_PUNTOVENTA', N'MODO_INGRESO_RAPIDO') IS NULL
    ALTER TABLE dbo.POS_PUNTOVENTA ADD MODO_INGRESO_RAPIDO nvarchar(20) NULL;

-- En otro lote (sp_executesql): en el mismo lote que el ALTER, SQL Server compila el UPDATE antes de que exista la columna
-- y falla con «El nombre de columna 'MODO_INGRESO_RAPIDO' no es válido».
EXEC sys.sp_executesql N'
UPDATE dbo.POS_PUNTOVENTA
SET MODO_INGRESO_RAPIDO = CASE WHEN ISNULL(CARGARAPIDAGRAFICA, 0) = 1 THEN N''COMPLETO'' ELSE N''DESHABILITADO'' END
WHERE MODO_INGRESO_RAPIDO IS NULL OR LTRIM(RTRIM(MODO_INGRESO_RAPIDO)) = N'''';';
