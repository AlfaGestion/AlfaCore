-- Identidad durable de las cargas sin pedido/remito; conserva operaciones anteriores.
IF OBJECT_ID(N'dbo.ALFACORE_VENTAS_CARGA_OPERACION',N'U') IS NULL RETURN;
IF COL_LENGTH(N'dbo.ALFACORE_VENTAS_CARGA_OPERACION',N'Borrador') IS NULL
    ALTER TABLE dbo.ALFACORE_VENTAS_CARGA_OPERACION ADD Borrador uniqueidentifier NULL;
GO
IF OBJECT_ID(N'dbo.ALFACORE_VENTAS_CARGA_OPERACION',N'U') IS NOT NULL
    AND NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'dbo.ALFACORE_VENTAS_CARGA_OPERACION')
        AND name=N'UX_ALFACORE_VENTAS_CARGA_BORRADOR')
    -- Compat 80: un índice filtrado hace fallar los INSERT/UPDATE de SqlClient (1934, ARITHABORT).
    AND (SELECT compatibility_level FROM sys.databases WHERE name = DB_NAME()) >= 90
    CREATE UNIQUE INDEX UX_ALFACORE_VENTAS_CARGA_BORRADOR ON dbo.ALFACORE_VENTAS_CARGA_OPERACION(Borrador)
        WHERE Borrador IS NOT NULL;
