SET NOCOUNT ON;
IF DB_NAME() NOT IN(N'ALFANET',N'ALFANET_DEMO') OR CONVERT(nvarchar(128),SERVERPROPERTY('ServerName'))<>N'SERVER-ALFAVB6'
 THROW 51000,'Destino de demostración incorrecto.',1;
SELECT
 (SELECT COUNT(*) FROM MA_CUENTAS) cuentas_totales,
 (SELECT COUNT(*) FROM VT_CLIENTES) clientes_totales,
 (SELECT COUNT(*) FROM V_MV_CPTE) comprobantes_totales,
 (SELECT COUNT(*) FROM MV_ASIENTOS) renglones_totales,
 (SELECT COUNT(*) FROM VT_CLIENTES WHERE LTRIM(RTRIM(CODIGO)) LIKE '112019%') clientes_demo,
 (SELECT COUNT(*) FROM V_MV_CPTE WHERE SUCURSAL='0099' AND NUMERO BETWEEN '80000001' AND '80999999') comprobantes_demo,
 (SELECT COUNT(*) FROM MV_ASIENTOS WHERE SUCURSAL='0099' AND [NUMERO ASIENTO] BETWEEN 80000001 AND 81000999) renglones_demo,
 (SELECT COUNT(*) FROM VE_CPTES_SALDOS_VENTAS WHERE LTRIM(RTRIM(CUENTA)) LIKE '112019%' AND SALDO>0) proformas_pendientes,
 (SELECT COUNT(*) FROM MV_ASIENTOS WHERE SUCURSAL='0099' AND [NUMERO ASIENTO] BETWEEN 80000001 AND 81000999
 AND (DATALENGTH(TC)<>DATALENGTH(RTRIM(TC)) OR DATALENGTH(CUENTA)<>DATALENGTH(RTRIM(CUENTA)))) rellenos_incorrectos,
 (SELECT COUNT(*) FROM (SELECT PERIODO,MES_OPERATIVO,[NUMERO ASIENTO],TIPO_REG FROM MV_ASIENTOS
 WHERE SUCURSAL='0099' AND [NUMERO ASIENTO] BETWEEN 80000001 AND 81000999
 GROUP BY PERIODO,MES_OPERATIVO,[NUMERO ASIENTO],TIPO_REG
 HAVING ABS(SUM(CASE WHEN [DEBE-HABER]='D' THEN IMPORTE ELSE -IMPORTE END))>0.001) x) asientos_desbalanceados,
 (SELECT COUNT(*) FROM TA_CONFIGURACION WHERE CLAVE='DEMO-CONCILIACION-202610') lote_sembrado,
 (SELECT ((LEN(j)-LEN(REPLACE(j,'111020901','')))+(LEN(j)-LEN(REPLACE(j,'111020902','')))+(LEN(j)-LEN(REPLACE(j,'111010904',''))))/9
 FROM (SELECT CONVERT(nvarchar(max),ValorAux) j FROM TA_CONFIGURACION WHERE CLAVE='CONCILIACION-ASIENTOS') cfg) reglas_demo,
 (SELECT COUNT(*) FROM sys.columns WHERE object_id=OBJECT_ID('BK_Conciliacion') AND name IN('DiferenciaImporte','ToleranciaImporte','MotivoDiferencia')) columnas_tolerancia,
 (SELECT COUNT(*) FROM sys.tables WHERE name IN('BK_AsientoOperacion','BK_ConciliacionIaAnalisis')) tablas_ia_asientos,
 (SELECT COUNT(*) FROM BK_ImportacionExtracto WHERE CuentaBanco IN('111020901','111020902','111010904')) importaciones_demo
FOR JSON PATH;
