SET NOCOUNT ON;

PRINT '=== 1. Configuración relevante (TA_CONFIGURACION) ===';
SELECT RTRIM(CLAVE) AS CLAVE, LEFT(CONVERT(nvarchar(max),VALOR),60) AS VALOR, RTRIM(GRUPO) AS GRUPO
FROM dbo.TA_CONFIGURACION
WHERE UPPER(RTRIM(CLAVE)) IN (N'MEZCLARPROFORMAS',N'USAFACTURAPROFORMA',N'USAPROFORMA',N'EQU_OPG',N'EQU_PG',
      N'NUM_OPG',N'NUM_PG',N'NUM_PGFP',N'CHEQUESXUNEGOCIO',N'PAGOSAPLICACIONAUTO',N'TIPOREGFACTURACION',
      N'CUENTAPROVEEDORESVARIOS',N'TITULOPROVEEDORES')
ORDER BY CLAVE;

PRINT '=== 2. Objetos clave: tipo (V/U) ===';
SELECT name, type_desc FROM sys.objects
WHERE name IN (N'CO_Cptes_Impagos',N'CO_Cptes_Creditos_Pendientes',N'CO_CPTES_IMPAGOS_2026',N'V_MV_CPTE',N'MV_ASIENTOS',
               N'MV_APLICACION',N'CO_PAGOS_REALIZADOS',N'MA_CUENTAS',N'MA_CUENTASADIC',N'VT_PROVEEDORES')
ORDER BY name;

PRINT '=== 3. Definición de las vistas de pendientes ===';
SELECT o.name, OBJECT_DEFINITION(o.object_id) AS definicion
FROM sys.objects o WHERE o.name IN (N'CO_Cptes_Impagos',N'CO_Cptes_Creditos_Pendientes') AND o.type='V';

PRINT '=== 4. Tablas candidatas de comprobantes / talonarios / contadores ===';
SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_NAME LIKE N'%COMPROB%' OR TABLE_NAME LIKE N'%TALON%' OR TABLE_NAME LIKE N'%ULTIMO%' OR TABLE_NAME LIKE N'%NUMER%'
ORDER BY TABLE_NAME;

PRINT '=== 5. Muestra de OPG / PG / PGFP existentes (cantidad por TC y año) ===';
SELECT RTRIM(TC) AS TC, YEAR(FECHA) AS Anio, COUNT(*) AS Cantidad, SUM(CASE WHEN Finalizada=1 THEN 1 ELSE 0 END) AS Finalizadas
FROM dbo.V_MV_CPTE WHERE RTRIM(TC) IN (N'OPG',N'PG',N'PGFP') GROUP BY RTRIM(TC), YEAR(FECHA) ORDER BY 1,2;

PRINT '=== 6. Últimas 5 OPG con sus líneas de asiento y aplicaciones ===';
SELECT TOP 5 RTRIM(TC) TC, SUCURSAL, NUMERO, LETRA, FECHA, RTRIM(CUENTA) CUENTA, IMPORTE, FINALIZADA, RTRIM(TCORIGEN) TCORIGEN,
       RTRIM(COMPROBANTEORIGEN) COMPROBANTEORIGEN, UNEGOCIO
FROM dbo.V_MV_CPTE WHERE RTRIM(TC)=N'OPG' ORDER BY FECHA DESC, NUMERO DESC;

SELECT TOP 20 RTRIM(a.TC) TC, a.SUCURSAL, a.NUMERO, a.LETRA, a.SECUENCIA, RTRIM(a.CUENTA) CUENTA, a.[DEBE-HABER] DH, a.IMPORTE,
       RTRIM(a.TIPO_REG) TIPO_REG, a.CABIMPORTE
FROM dbo.MV_ASIENTOS a
JOIN (SELECT TOP 1 TC,SUCURSAL,NUMERO,LETRA FROM dbo.V_MV_CPTE WHERE RTRIM(TC)=N'OPG' ORDER BY FECHA DESC, NUMERO DESC) u
  ON a.TC=u.TC AND a.SUCURSAL=u.SUCURSAL AND a.NUMERO=u.NUMERO AND a.LETRA=u.LETRA
ORDER BY a.SECUENCIA;

SELECT TOP 20 RTRIM(TC) TC, SUCURSAL, NUMERO, LETRA, RTRIM(TCO_ORIGEN) TCO_ORIGEN, SUCURSAL_ORIGEN, NUMERO_ORIGEN, LETRA_ORIGEN,
       IMPORTE, RTRIM(TC_PRINT) TC_PRINT, RTRIM(IDCOMPROBANTE_PRINT) IDCOMPROBANTE_PRINT
FROM dbo.MV_APLICACION WHERE RTRIM(TC_PRINT) IN (N'OPG',N'PG',N'PGFP') ORDER BY NUMERO DESC;

